export function pickLine({ tags = [], recent = [], rng = Math.random }) {
  const recentSet = new Set(recent);
  const wanted = Array.isArray(tags) ? tags : [tags];
  // Try each tag in order, then fall back to general.
  for (const tag of [...wanted, 'general']) {
    const pool = SALON_LINES.filter((l) => l.tag === tag && !recentSet.has(l.text));
    if (pool.length > 0) return pool[Math.floor(rng() * pool.length)].text;
  }
  // Everything recent? Fall back to any general line.
  const anyPool = SALON_LINES.filter((l) => l.tag === 'general');
  return anyPool[Math.floor(rng() * anyPool.length)].text;
}
